# 3. КОМПЛЕКСНЫЙ ТЕСТ (ПОЛНАЯ ВАЛИДАЦИЯ)
# ============================================================

def test_order_create_dto_full_validation():
    """
    Проверка, что DTO создаётся только с полностью корректными данными.
    
    AAA-сценарий:
    - ARRANGE: подготовка валидных и невалидных данных
    - ACT: создание DTO в 3 разных сценариях
    - ASSERT: проверка всех результатов
    """
    # ═══════════════════════════════════════════════════════════
    # ARRANGE (Подготовка)
    # ═══════════════════════════════════════════════════════════
    valid_phone = '+79991234567'
    valid_email = 'user@example.com'
    invalid_phone = '123'
    invalid_email = 'bad-email'
    
    # ═══════════════════════════════════════════════════════════
    # ACT (Действие)
    # ═══════════════════════════════════════════════════════════
    # Сценарий 1: Валидные данные
    dto = OrderCreateDTO(phone=valid_phone, email=valid_email)
    
    # Сценарий 2: Невалидный телефон
    with pytest.raises(ValidationError) as exc1:
        OrderCreateDTO(phone=invalid_phone, email=valid_email)
    
    # Сценарий 3: Невалидный email
    with pytest.raises(ValidationError) as exc2:
        OrderCreateDTO(phone=valid_phone, email=invalid_email)
    
    # ═══════════════════════════════════════════════════════════
    # ASSERT (Проверка)
    # ═══════════════════════════════════════════════════════════
    assert dto.phone == valid_phone
    assert dto.email == valid_email
    assert 'Некорректный номер телефона' in str(exc1.value)
    assert 'value_error' in str(exc2.value).lower() or 'validation' in str(exc2.value).lower()


