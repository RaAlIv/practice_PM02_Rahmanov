# 1. ТЕСТЫ ВАЛИДАЦИИ ТЕЛЕФОННЫХ НОМЕРОВ
# ============================================================

@pytest.mark.parametrize('phone,expected_valid', [
    # ---- КОРРЕКТНЫЕ номера (должны проходить валидацию) ----
    ('+79991234567', True),
    ('89991234567', True),
    ('+7-999-123-45-67', True),
    ('+7 999 123 45 67', True),
    ('+7(999)123-45-67', True),
    
    # ---- НЕКОРРЕКТНЫЕ номера (должны выбрасывать ошибку) ----
    ('123', False),                   # слишком короткий
    ('abc', False),                   # буквы
    ('+7999123456', False),           # 10 цифр (не хватает)
    ('+799912345678', False),         # 12 цифр (перебор)
    ('+1-999-123-45-67', False),      # не Россия
])
def test_phone_validation(phone: str, expected_valid: bool):
    """
    Проверка валидации телефонных номеров.
    Ожидаем успех для корректных, ошибку для некорректных.
    
    AAA-сценарий:
    - ARRANGE: входные данные из параметризации
    - ACT: создание DTO или перехват исключения
    - ASSERT: проверка нормализации или наличия ошибки
    """
    # ═══════════════════════════════════════════════════════════
    # ARRANGE (Подготовка) - данные из параметризации
    # ═══════════════════════════════════════════════════════════
    email = 'test@example.com'
    
    # ═══════════════════════════════════════════════════════════
    # ACT (Действие) - выполняем тестируемый код
    # ═══════════════════════════════════════════════════════════
    if expected_valid:
        dto = OrderCreateDTO(phone=phone, email=email)
    else:
        with pytest.raises(ValidationError):
            OrderCreateDTO(phone=phone, email=email)
        return
    
    # ═══════════════════════════════════════════════════════════
    # ASSERT (Проверка) - проверяем результат
    # ═══════════════════════════════════════════════════════════
    if phone.startswith('8'):
        assert dto.phone == '+7' + phone[1:]
    else:
        expected = re.sub(r'[^\d+]', '', phone)
        assert dto.phone == expected


